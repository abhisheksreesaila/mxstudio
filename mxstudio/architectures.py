def _gap_markdown(gaps: list[dict]) -> str:
    lines = []
    for g in gaps:
        mark = {"builtin": "[built-in]", "done": "[x]", "missing": "[ ]"}.get(
            g["status"], "[ ]"
        )
        lines.append(f"- {mark} **{g['title']}** (`{g['file']}`) — {g['detail']}")
    return "\n".join(lines)
